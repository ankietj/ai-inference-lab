"""Transparent request workload simulator for LLM inference analysis.

DISCLAIMER AND MODELING BOUNDARIES:
-----------------------------------
This simulator is a first-principles, analytical discrete-event workload model.
It is intended to study the directional scaling laws of LLM serving (e.g., prompt length,
output length, concurrency, and KV-cache footprint).

WHAT THIS SIMULATOR MODELS:
1. Prefill service time based on model FLOPs (linear projection FLOPs + quadratic attention FLOPs)
   and hardware compute/memory rooflines.
2. Decode step service time based on memory bandwidth roofline (loading model weights + active KV-cache).
3. Concurrency batching amortization: loading static model weights once per step to advance multiple streams.
4. Admission queueing delay and continuous step interleaving (admitting at most one pending prefill
   per scheduling iteration before advancing decode steps).
5. Exact KV-cache memory consumption tracking (continuous and block-allocated in MiB/GiB).

WHAT THIS SIMULATOR DOES NOT CLAIM TO MODEL:
- It does NOT replicate proprietary CUDA kernel implementations, driver jitter, or PCIe transfers.
- It does NOT claim to predict exact millisecond latencies of vLLM or TensorRT-LLM on arbitrary hardware.
- Real inference engine validation requires physical GPU execution (see colab validation guide).
"""

from __future__ import annotations

import math
import platform
import sys
import time
from dataclasses import asdict, dataclass, field
from typing import Any

from inference_lab.hardware import HardwareConfig
from inference_lab.memory import (
    kv_cache_blocked_bytes,
    kv_cache_bytes_per_token,
    max_active_tokens_in_vram,
    model_weights_bytes,
)
from inference_lab.models import ModelConfig, Precision


@dataclass
class Request:
    """Individual user request submitted to the inference server."""
    request_id: int
    arrival_time: float      # Seconds from simulation start
    prompt_length: int       # Input prompt tokens
    output_length: int       # Target generated output tokens

    # Execution telemetry populated during simulation:
    start_time: float = -1.0
    prefill_end_time: float = -1.0
    finish_time: float = -1.0
    generated_tokens: int = 0

    @property
    def queue_time(self) -> float:
        """Time spent waiting in queue before prefill begins (seconds)."""
        return max(0.0, self.start_time - self.arrival_time) if self.start_time >= 0 else 0.0

    @property
    def prefill_service_time(self) -> float:
        """Active GPU service latency dedicated to executing prefill (seconds)."""
        if self.prefill_end_time >= 0 and self.start_time >= 0:
            return max(0.0, self.prefill_end_time - self.start_time)
        return 0.0

    @property
    def ttft(self) -> float:
        """Time To First Token: from request arrival until the first token is emitted (seconds).

        Identity: TTFT == queue_time + prefill_service_time (within floating point precision).
        """
        return max(0.0, self.prefill_end_time - self.arrival_time) if self.prefill_end_time >= 0 else 0.0

    @property
    def tpot(self) -> float:
        """Time Per Output Token: average latency per decode step (seconds).

        Token 1 is generated by the prefill phase at prefill_end_time.
        Subsequent autoregressive decode steps produce (output_length - 1) tokens.

        Explicit Edge-Case Behavior:
        - If output_length <= 1: Only the prefill token (or 0 tokens) was emitted.
          No decode intervals occurred. Returns 0.0.
        - If output_length > 1: returns (finish_time - prefill_end_time) / (generated_tokens - 1).
        """
        decode_tokens = self.generated_tokens - 1
        if decode_tokens <= 0:
            return 0.0
        decode_duration = self.finish_time - self.prefill_end_time
        return max(0.0, decode_duration / decode_tokens)

    @property
    def e2e_latency(self) -> float:
        """Total end-to-end request turnaround latency from arrival to completion (seconds)."""
        return max(0.0, self.finish_time - self.arrival_time) if self.finish_time >= 0 else 0.0


@dataclass
class SimulationConfig:
    """Configuration governing the simulation run."""
    model: ModelConfig
    hardware: HardwareConfig
    precision: Precision = Precision.FP16
    max_concurrency: int = 16
    block_size: int = 16
    kernel_launch_overhead_s: float = 20e-6  # 20 microseconds per kernel launch
    random_seed: int = 42


@dataclass
class SimulationResult:
    """Complete results, statistical metrics, and metadata from a simulation run."""
    config: SimulationConfig
    requests: list[Request]
    makespan_s: float
    total_prompt_tokens: int
    total_output_tokens: int
    avg_queue_time_s: float
    p50_queue_time_s: float
    p90_queue_time_s: float
    p99_queue_time_s: float
    avg_prefill_service_time_s: float
    p50_prefill_service_time_s: float
    p90_prefill_service_time_s: float
    p99_prefill_service_time_s: float
    avg_ttft_s: float
    p50_ttft_s: float
    p90_ttft_s: float
    p99_ttft_s: float
    avg_tpot_s: float
    p50_tpot_s: float
    p90_tpot_s: float
    p99_tpot_s: float
    avg_e2e_latency_s: float
    p50_e2e_latency_s: float
    p90_e2e_latency_s: float
    p99_e2e_latency_s: float
    tokens_per_second: float
    peak_kv_cache_bytes: float
    environment_metadata: dict[str, Any] = field(default_factory=dict)

    def summary_dict(self) -> dict[str, Any]:
        """Serializable dictionary for experiment logging."""
        return {
            "model": self.config.model.name,
            "hardware": self.config.hardware.name,
            "precision": self.config.precision.value,
            "max_concurrency": self.config.max_concurrency,
            "num_requests": len(self.requests),
            "makespan_s": round(self.makespan_s, 4),
            "total_prompt_tokens": self.total_prompt_tokens,
            "total_output_tokens": self.total_output_tokens,
            "throughput_tokens_per_s": round(self.tokens_per_second, 2),
            "avg_queue_time_ms": round(self.avg_queue_time_s * 1000, 2),
            "p50_queue_time_ms": round(self.p50_queue_time_s * 1000, 2),
            "avg_prefill_service_ms": round(self.avg_prefill_service_time_s * 1000, 2),
            "p50_prefill_service_ms": round(self.p50_prefill_service_time_s * 1000, 2),
            "avg_ttft_ms": round(self.avg_ttft_s * 1000, 2),
            "p50_ttft_ms": round(self.p50_ttft_s * 1000, 2),
            "p95_ttft_ms": round(self.p90_ttft_s * 1000, 2),
            "avg_tpot_ms": round(self.avg_tpot_s * 1000, 3),
            "p50_tpot_ms": round(self.p50_tpot_s * 1000, 3),
            "avg_e2e_ms": round(self.avg_e2e_latency_s * 1000, 2),
            "p95_e2e_ms": round(self.p90_e2e_latency_s * 1000, 2),
            "peak_kv_cache_mib": round(self.peak_kv_cache_bytes / (1024**2), 2),
            "metadata": self.environment_metadata,
        }


class SimpleWorkloadSimulator:
    """Discrete workload simulator executing request queues under hardware rooflines."""

    def __init__(self, config: SimulationConfig) -> None:
        self.config = config
        self.bytes_per_token = kv_cache_bytes_per_token(config.model, config.precision)
        self.weights_bytes = model_weights_bytes(config.model, config.precision)
        self.max_kv_tokens = max_active_tokens_in_vram(
            config.model, config.hardware, config.precision
        )

    def compute_prefill_time(self, prompt_tokens: int) -> float:
        """Calculate prefill execution time for prompt_tokens under hardware roofline.

        Prefill FLOPs consists of:
        1. Linear projections (Q, K, V, O, and MLP layers): 2 * num_params * prompt_tokens
        2. Attention matrix multiplications (QK^T and Softmax(A)V):
           4 * n_layers * d_model * prompt_tokens^2
        """
        model = self.config.model
        hw = self.config.hardware

        # Compute bound calculation (including quadratic attention FLOPs):
        linear_flops = 2.0 * model.num_params * prompt_tokens
        attention_flops = 4.0 * model.n_layers * model.d_model * (prompt_tokens**2)
        total_flops = linear_flops + attention_flops
        compute_time = total_flops / hw.effective_fp16_flops_s

        # Memory bandwidth bound calculation:
        kv_bytes = prompt_tokens * self.bytes_per_token
        memory_time = (self.weights_bytes + kv_bytes) / hw.effective_memory_bandwidth_bytes_s

        # Roofline model: bounded by the slower of compute or memory bandwidth
        base_time = max(compute_time, memory_time)
        return base_time + self.config.kernel_launch_overhead_s

    def compute_decode_step_time(self, active_requests: list[Request]) -> float:
        """Calculate latency of a single decode step generating 1 token across all active requests.

        In decode, arithmetic intensity is low (GEMV).
        Latency is dominated by reading model weights and each active sequence's KV-cache.
        """
        if not active_requests:
            return 0.0

        b = len(active_requests)
        # Sum of current context lengths across active requests
        total_context_tokens = sum(
            req.prompt_length + req.generated_tokens for req in active_requests
        )
        total_kv_bytes = total_context_tokens * self.bytes_per_token

        # Total memory loaded in this decode step:
        bytes_transferred = self.weights_bytes + total_kv_bytes
        transfer_time = bytes_transferred / self.config.hardware.effective_memory_bandwidth_bytes_s

        # Compute FLOPs for B tokens:
        flops = 2.0 * self.config.model.num_params * b
        compute_time = flops / self.config.hardware.effective_fp16_flops_s

        step_time = max(transfer_time, compute_time) + self.config.kernel_launch_overhead_s
        return step_time

    def run(self, requests: list[Request]) -> SimulationResult:
        """Execute the batch of requests and collect complete performance telemetry.

        Scheduling Policy:
        - At most one pending request is admitted and prefilled per scheduling iteration.
        - Existing active requests execute a decode step in every iteration where decode
          tokens are pending, avoiding serial prefill head-of-line blocking across the batch.
        """
        # Sort requests by arrival time
        pending_queue = sorted(requests, key=lambda r: r.arrival_time)
        active_requests: list[Request] = []
        completed_requests: list[Request] = []

        current_time = 0.0
        peak_kv_bytes = 0.0

        while pending_queue or active_requests:
            # If no active requests, advance clock to next arrival
            if not active_requests and pending_queue:
                current_time = max(current_time, pending_queue[0].arrival_time)

            # 1. Admission: Admit AT MOST ONE pending request per scheduling iteration.
            # This allows active requests to decode incrementally between admissions.
            if pending_queue and len(active_requests) < self.config.max_concurrency:
                next_req = pending_queue[0]
                if next_req.arrival_time <= current_time:
                    current_active_tokens = sum(
                        r.prompt_length + r.output_length for r in active_requests
                    )
                    vram_ok = (
                        (current_active_tokens + next_req.prompt_length <= self.max_kv_tokens)
                        if self.max_kv_tokens > 0
                        else True
                    )
                    if vram_ok:
                        req = pending_queue.pop(0)
                        req.start_time = current_time

                        # Execute prefill: GPU is dedicated to prefill during this interval
                        prefill_duration = self.compute_prefill_time(req.prompt_length)
                        current_time += prefill_duration
                        req.prefill_end_time = current_time

                        # First token emitted at end of prefill
                        req.generated_tokens = 1
                        if req.generated_tokens >= req.output_length:
                            # 1-token output request completes immediately
                            req.finish_time = current_time
                            completed_requests.append(req)
                        else:
                            active_requests.append(req)

            # Track peak KV cache memory usage
            if active_requests:
                peak_kv_bytes = max(
                    peak_kv_bytes,
                    sum(
                        kv_cache_blocked_bytes(
                            self.config.model,
                            r.prompt_length + r.generated_tokens,
                            self.config.precision,
                            self.config.block_size,
                        )
                        for r in active_requests
                    ),
                )

                # 2. Decode Step: Run 1 decode step across all currently active requests
                step_duration = self.compute_decode_step_time(active_requests)
                current_time += step_duration

                # Advance generated tokens and check completions
                still_active: list[Request] = []
                for req in active_requests:
                    req.generated_tokens += 1
                    if req.generated_tokens >= req.output_length:
                        req.finish_time = current_time
                        completed_requests.append(req)
                    else:
                        still_active.append(req)

                active_requests = still_active

        # Compute summary metrics
        completed_requests.sort(key=lambda r: r.request_id)
        return self._build_result(completed_requests, current_time, peak_kv_bytes)

    def _build_result(
        self, requests: list[Request], makespan: float, peak_kv_bytes: float
    ) -> SimulationResult:
        n = len(requests)
        if n == 0:
            raise ValueError("No requests were processed in the simulation.")

        ttfts = sorted(r.ttft for r in requests)
        queues = sorted(r.queue_time for r in requests)
        prefills = sorted(r.prefill_service_time for r in requests)
        tpots = sorted(r.tpot for r in requests)
        e2es = sorted(r.e2e_latency for r in requests)

        def percentile(data: list[float], p: float) -> float:
            k = (len(data) - 1) * p
            f = math.floor(k)
            c = math.ceil(k)
            if f == c:
                return data[int(k)]
            return data[f] * (c - k) + data[c] * (k - f)

        total_prompt_tokens = sum(r.prompt_length for r in requests)
        total_output_tokens = sum(r.generated_tokens for r in requests)
        throughput = total_output_tokens / makespan if makespan > 0 else 0.0

        metadata = {
            "python_version": sys.version.split()[0],
            "platform": platform.platform(),
            "random_seed": self.config.random_seed,
            "timestamp_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "assumptions": [
                "Prefill time = max((Linear_FLOPs + Attention_FLOPs) / Peak_FLOPS, Bytes / Peak_BW) + kernel_overhead",
                "Decode step time = max(Weights+KV_cache / Peak_BW, FLOPs / Peak_FLOPS) + kernel_overhead",
                "Interleaved continuous batching (admit at most 1 prefill per iteration before decode)",
                "Analytical roofline model: does not model CUDA kernel launch latency jitter or NCCL communication",
            ],
            "units": {
                "memory": "MiB (1024^2 bytes) / GiB (1024^3 bytes)",
                "latency": "seconds / milliseconds",
                "throughput": "output tokens / second",
            },
        }

        return SimulationResult(
            config=self.config,
            requests=requests,
            makespan_s=makespan,
            total_prompt_tokens=total_prompt_tokens,
            total_output_tokens=total_output_tokens,
            avg_queue_time_s=sum(queues) / n,
            p50_queue_time_s=percentile(queues, 0.50),
            p90_queue_time_s=percentile(queues, 0.90),
            p99_queue_time_s=percentile(queues, 0.99),
            avg_prefill_service_time_s=sum(prefills) / n,
            p50_prefill_service_time_s=percentile(prefills, 0.50),
            p90_prefill_service_time_s=percentile(prefills, 0.90),
            p99_prefill_service_time_s=percentile(prefills, 0.99),
            avg_ttft_s=sum(ttfts) / n,
            p50_ttft_s=percentile(ttfts, 0.50),
            p90_ttft_s=percentile(ttfts, 0.90),
            p99_ttft_s=percentile(ttfts, 0.99),
            avg_tpot_s=sum(tpots) / n,
            p50_tpot_s=percentile(tpots, 0.50),
            p90_tpot_s=percentile(tpots, 0.90),
            p99_tpot_s=percentile(tpots, 0.99),
            avg_e2e_latency_s=sum(e2es) / n,
            p50_e2e_latency_s=percentile(e2es, 0.50),
            p90_e2e_latency_s=percentile(e2es, 0.90),
            p99_e2e_latency_s=percentile(e2es, 0.99),
            tokens_per_second=throughput,
            peak_kv_cache_bytes=peak_kv_bytes,
            environment_metadata=metadata,
        )
